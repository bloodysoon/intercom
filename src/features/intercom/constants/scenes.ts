export const SCENE_IDS: readonly SceneId[] = SCENES.map((s) => s.id);

export const SCREENPLAY_SCENE_TITLES: Record<ScreenplayScene, string> = {
  2: "Sc. 2 — Intrarea palatului",
  3: "Sc. 3 — În palat",
};

const SCENE_MAP = new Map<SceneId, SceneDefinition>(SCENES.map((s) => [s.id, s]));

export function getScene(id: SceneId): SceneDefinition {
  const scene = SCENE_MAP.get(id);
  if (!scene) throw new Error(`Unknown scene: ${id}`);
  return scene;
}

export function sceneIndex(id: SceneId): number {
  return SCENE_IDS.indexOf(id);
}

export function isSceneId(value: unknown): value is SceneId {
  return typeof value === "string" && SCENE_MAP.has(value as SceneId);
}

export const INITIAL_SCENE: SceneId = "standby";
export const UNLOCKED_SCENE: SceneId = "unlocked";

/** The door stays open from the unlock onwards (Sc. 3 takes place inside). */
export function isDoorOpen(id: SceneId): boolean {
  return sceneIndex(id) >= sceneIndex(UNLOCKED_SCENE);
}
